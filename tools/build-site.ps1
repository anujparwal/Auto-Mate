<#
.SYNOPSIS
Builds the static download site and an allowlisted Windows source package under dist/site.
.DESCRIPTION
Requires Windows PowerShell 5.1+. No vault, environment file, conversation memory,
Git directory, dependency cache, or machine-specific .local directory is packaged.
The ZIP contains source and a prerequisite installer, not a signed application binary.
#>
[CmdletBinding()]
param()
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if ($env:OS -ne 'Windows_NT') { throw 'Build the Windows package on Windows.' }
$root = Split-Path -Parent $PSScriptRoot
$output = Join-Path $root 'dist/site'
$staging = Join-Path ([IO.Path]::GetTempPath()) ('AutoMate-Release-' + [guid]::NewGuid().ToString('N'))
$entries = @('package.json', 'bun.lock', 'tsconfig.json', 'README.md', 'CHANGELOG.md', 'use.md', 'src', 'ui', 'tools', 'tests', 'platforms/windows', 'site', 'docs')
try {
    New-Item -ItemType Directory -Path $staging | Out-Null
    foreach ($entry in $entries) {
        $source = Join-Path $root $entry
        if (-not (Test-Path -LiteralPath $source)) { throw ('Required package source missing: ' + $entry) }
        $items = @(Get-Item -LiteralPath $source -Force)
        if (Test-Path -LiteralPath $source -PathType Container) { $items += @(Get-ChildItem -LiteralPath $source -Recurse -Force) }
        foreach ($item in $items) {
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw ('Refusing a linked package source: ' + $item.Name) }
            if ($item.Name -match '^(\.env(?:\..*)?|\.git|\.local|node_modules|vault\.json)$' -or $item.Name -match '\.(vault(?:\.json)?|pem|pfx|p12|key|keystore|jks)$') {
                throw ('Refusing a private or generated package source: ' + $item.Name)
            }
        }
        $target = Join-Path $staging $entry
        New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null
        Copy-Item -LiteralPath $source -Destination $target -Recurse
    }
    # This directory is generated by this script; no user-selected output path is accepted.
    if (Test-Path -LiteralPath $output) { Remove-Item -LiteralPath $output -Recurse -Force }
    New-Item -ItemType Directory -Path $output -Force | Out-Null
    Copy-Item -LiteralPath (Join-Path $root 'site/index.html'), (Join-Path $root 'site/styles.css'), (Join-Path $root 'use.md') -Destination $output
    Copy-Item -LiteralPath (Join-Path $root 'docs/model-api.md') -Destination (Join-Path $output 'model-api.md')
    Set-Content -LiteralPath (Join-Path $output '.nojekyll') -Value '' -Encoding Ascii
    $archive = Join-Path $output 'Auto-Mate-windows.zip'
    Compress-Archive -Path (Join-Path $staging '*') -DestinationPath $archive -CompressionLevel Optimal
    $hash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
    Set-Content -LiteralPath (Join-Path $output 'SHA256SUMS.txt') -Value ($hash + '  Auto-Mate-windows.zip') -Encoding Ascii
    Write-Host 'Built dist/site: static HTML/CSS, usage/model guides, Windows source ZIP, and SHA-256 checksum.'
    Write-Host 'No deployment performed. This is an unsigned development preview; normal Windows Hello remains required.'
} finally {
    if (Test-Path -LiteralPath $staging) { Remove-Item -LiteralPath $staging -Recurse -Force }
}
